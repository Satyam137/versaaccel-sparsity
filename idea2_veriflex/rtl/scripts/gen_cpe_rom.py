#!/usr/bin/env python3
"""
gen_cpe_rom.py -- turn the CPE's .hex weight files into a synthesizable ROM.

Why this exists
---------------
config_prediction_engine.sv loads its INT8 weights with $readmemh inside an
`initial` block. Simulators honour that; synthesis does not. Genus ignores the
initial block, leaving w1/b1/... as registers that nothing ever writes -- so
constant propagation deletes the entire CPE and the reported area is a lie
(roughly zero) rather than an over- or under-estimate.

This script emits cpe_weights_rom.svh, a set of `localparam` arrays holding the
same values. config_prediction_engine.sv includes it under `ifdef SYNTHESIS`,
so simulation keeps using $readmemh (and the golden test keeps proving the two
agree) while synthesis sees constants and infers a real ROM.

Run after retraining the CPE:
    python3 idea2_veriflex/rtl/scripts/gen_cpe_rom.py
"""
import os
import sys

RTL = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WEIGHTS = os.path.join(RTL, "weights")
OUT = os.path.join(RTL, "versaaccel_rtl", "cpe_weights_rom.svh")

# name -> (dims, signed)   dims innermost-last, matching the SV declaration
ARRAYS = [
    ("w1",       (16, 9),  True),
    ("b1",       (16,),    True),
    ("w2",       (16, 16), True),
    ("b2",       (16,),    True),
    ("w3",       (5, 16),  True),
    ("b3",       (5,),     True),
    ("shift_mem", (3,),    False),
]


def read_hex(name, count):
    path = os.path.join(WEIGHTS, f"cpe_{name}.hex" if name != "shift_mem"
                        else "cpe_shifts.hex")
    if not os.path.exists(path):
        sys.exit(f"missing {path} -- run idea2_veriflex/train_cpe_classifier.py first")
    vals = []
    with open(path) as f:
        for line in f:
            line = line.split("//")[0].strip()
            if line:
                vals.extend(int(t, 16) for t in line.split())
    if len(vals) != count:
        sys.exit(f"{path}: expected {count} values, found {len(vals)}")
    return vals


def main():
    lines = [
        "// cpe_weights_rom.svh -- GENERATED by scripts/gen_cpe_rom.py, do not edit.",
        "// Synthesis view of the CPE weights. Simulation uses $readmemh on the same",
        "// .hex files; tb_cpe_golden proves the two are the same numbers.",
        "//",
        "// Emitted as element-wise assignments rather than unpacked-array localparams:",
        "// both are legal SV-2012 and synthesise to the same constants, but this form",
        "// also elaborates in iverilog, so the synthesis view can be simulated and",
        "// checked against the $readmemh view instead of being taken on trust.",
        "// Intended to be included inside an always_comb block.",
        "",
    ]
    total = 0
    for name, dims, signed in ARRAYS:
        count = 1
        for d in dims:
            count *= d
        vals = read_hex(name, count)
        lines.append(f"// {name} {'x'.join(str(d) for d in dims)}")
        if len(dims) == 1:
            for i, v in enumerate(vals):
                lines.append(f"{name}[{i}] = 8'h{v:02x};")
        else:
            inner = dims[-1]
            for r in range(dims[0]):
                for c in range(inner):
                    lines.append(f"{name}[{r}][{c}] = 8'h{vals[r * inner + c]:02x};")
        total += count
        lines.append("")

    with open(OUT, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {OUT}  ({total} constants)")


if __name__ == "__main__":
    main()
